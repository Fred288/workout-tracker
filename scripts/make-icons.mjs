// Generates the PWA icons: the flexed-biceps emoji (Twemoji, CC BY 4.0) on the app's dark background.
// Run: npm run icons
import sharp from 'sharp';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';

const EMOJI_URL = 'https://raw.githubusercontent.com/jdecked/twemoji/main/assets/svg/1f4aa.svg';
const BG = '#0b0b0f';
// Keep the emoji inside the maskable safe zone (inner 80% circle) so Android masks never crop it.
const EMOJI_SCALE = 0.58;

const res = await fetch(EMOJI_URL);
if (!res.ok) throw new Error(`Twemoji download failed: HTTP ${res.status}`);
const svg = Buffer.from(await res.text());

async function icon(size) {
  const emoji = Math.round(size * EMOJI_SCALE);
  const glyph = await sharp(svg, { density: 600 }).resize(emoji, emoji).png().toBuffer();
  return sharp({ create: { width: size, height: size, channels: 4, background: BG } })
    .composite([{ input: glyph, gravity: 'center' }])
    .png()
    .toBuffer();
}

await mkdir('public', { recursive: true });
await writeFile('public/icon-192.png', await icon(192));
await writeFile('public/icon-512.png', await icon(512));
await writeFile('public/apple-touch-icon.png', await icon(180));

// iOS launch screens ("splash"): one image per device size, picked by media query.
// [css width, css height, pixel ratio] of iPhones in portrait.
const IPHONES = [
  [440, 956, 3], // 16 Pro Max
  [402, 874, 3], // 16 Pro
  [430, 932, 3], // 15/14 Pro Max, 15 Plus, 16 Plus
  [393, 852, 3], // 15, 15 Pro, 14 Pro, 16
  [428, 926, 3], // 13/12 Pro Max, 14 Plus
  [390, 844, 3], // 14, 13, 13 Pro, 12, 12 Pro
  [375, 812, 3], // X, XS, 11 Pro, 13 mini, 12 mini
  [414, 896, 3], // XS Max, 11 Pro Max
  [414, 896, 2], // XR, 11
  [375, 667, 2], // SE (2nd/3rd gen), 8
];

async function splash(w, h) {
  const glyphSize = Math.round(Math.min(w, h) * 0.3);
  const glyph = await sharp(svg, { density: 600 }).resize(glyphSize, glyphSize).png().toBuffer();
  return sharp({ create: { width: w, height: h, channels: 4, background: BG } })
    .composite([{ input: glyph, gravity: 'center' }])
    .png({ compressionLevel: 9 })
    .toBuffer();
}

await rm('public/splash', { recursive: true, force: true });
await mkdir('public/splash', { recursive: true });
const links = [];
for (const [cw, ch, ratio] of IPHONES) {
  const name = `splash-${cw * ratio}x${ch * ratio}.png`;
  await writeFile(`public/splash/${name}`, await splash(cw * ratio, ch * ratio));
  links.push(
    `    <link rel="apple-touch-startup-image" href="splash/${name}" media="(device-width: ${cw}px) and (device-height: ${ch}px) and (-webkit-device-pixel-ratio: ${ratio}) and (orientation: portrait)" />`,
  );
}

// Keep index.html in sync between the markers.
const html = await readFile('index.html', 'utf8');
const block = `    <!-- splash:start (generated by npm run icons) -->\n${links.join('\n')}\n    <!-- splash:end -->`;
const next = html.replace(/ {4}<!-- splash:start[\s\S]*?<!-- splash:end -->/, block);
if (next === html && !html.includes('splash:start')) throw new Error('index.html is missing the splash markers');
await writeFile('index.html', next);
console.log(`Icons and ${IPHONES.length} splash screens written`);
